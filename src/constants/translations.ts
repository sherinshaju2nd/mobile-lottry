export function getDistrictTranslatedName(
  district: string,
  lang: Language,
): string {
  if (!district) return "";
  if (lang === "en") return district;
  const key = district.trim().toLowerCase();
  const entry = DISTRICT_NAMES_BY_LANG[key];
  if (!entry) return district;
  return entry[lang] || district;
}
